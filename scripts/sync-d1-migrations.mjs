#!/usr/bin/env node
/**
 * Projects Prisma's migrations into the flat layout `wrangler d1 migrations`
 * expects, so production migrations are *tracked* instead of applied by hand.
 *
 * Why this exists: applying schema changes to D1 by pasting SQL into a console
 * left nothing recording what had already run. That cost us twice — once when a
 * deployed page queried a table that was never created, and once when a
 * point-in-time restore rolled the schema away and the only recovery was a
 * hand-generated rescue script. `wrangler d1 migrations apply` keeps its own
 * ledger in the database, so it can work out what's outstanding by itself.
 *
 * The two tools disagree about layout and neither will change:
 *   Prisma:   prisma/migrations/<timestamp>_<name>/migration.sql   (a folder)
 *   Wrangler: migrations/<name>.sql                                (a flat file)
 *
 * So Prisma stays the thing you author with (`npm run db:migrate` still works
 * normally) and this copies the result across. Filenames keep Prisma's
 * timestamp prefix, which both preserves apply order under Wrangler's
 * lexicographic sort and keeps a 1:1 trail back to the source folder.
 *
 * Run `npm run cf:migrations:check` in CI to prove the two are in step.
 */

import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";

const PRISMA_DIR = path.join(process.cwd(), "prisma", "migrations");
const OUT_DIR = path.join(process.cwd(), "migrations");

const checkOnly = process.argv.includes("--check");

function fail(message) {
  console.error(`\n✖ ${message}\n`);
  process.exit(1);
}

function prismaMigrations() {
  if (!existsSync(PRISMA_DIR)) fail(`No migrations directory at ${PRISMA_DIR}.`);

  return readdirSync(PRISMA_DIR)
    .filter((entry) => statSync(path.join(PRISMA_DIR, entry)).isDirectory())
    .sort()
    .map((folder) => {
      const source = path.join(PRISMA_DIR, folder, "migration.sql");
      if (!existsSync(source)) {
        fail(`${folder} has no migration.sql — did a migration get half-created?`);
      }
      return { folder, source, target: path.join(OUT_DIR, `${folder}.sql`) };
    });
}

function digest(text) {
  return createHash("sha256").update(text).digest("hex").slice(0, 12);
}

const migrations = prismaMigrations();
mkdirSync(OUT_DIR, { recursive: true });

const changed = [];
const created = [];
const rewritten = [];

for (const { folder, source, target } of migrations) {
  const sql = readFileSync(source, "utf8");
  const header =
    `-- Generated by scripts/sync-d1-migrations.mjs from\n` +
    `--   prisma/migrations/${folder}/migration.sql\n` +
    `-- Do not edit this file. Edit prisma/schema.prisma and run\n` +
    `--   npm run db:migrate && npm run cf:migrations:sync\n\n`;
  const next = header + sql;

  if (!existsSync(target)) {
    created.push(folder);
    if (!checkOnly) writeFileSync(target, next);
    continue;
  }

  const current = readFileSync(target, "utf8");

  // Compared with line endings normalised, never raw. The header above is
  // built with LF, but Git on Windows checks these files back out as CRLF
  // (core.autocrlf), so a raw comparison reports every migration as edited on
  // a Windows working copy while passing on Linux CI. That is a line-ending
  // artefact, not drift - and left unfixed it drowns out the genuine
  // "someone edited an already-applied migration" hazard this check exists
  // to catch.
  const normalise = (text) => text.replace(/\r\n/g, "\n");
  if (normalise(current) === normalise(next)) continue;

  // A migration whose contents changed after it was synced is a hazard, not a
  // routine update: the old version may already be applied to production, and
  // Wrangler tracks migrations by name, so it will never re-run this one to
  // pick up the difference. Editing applied migrations is the mistake here —
  // add a new migration instead.
  const stripComments = (text) => normalise(text).replace(/^--[^\n]*\n/gm, "");
  const bodyChanged = stripComments(current) !== stripComments(next);
  if (bodyChanged) {
    changed.push({ folder, was: digest(current), now: digest(next) });
  } else {
    rewritten.push(folder);
    if (!checkOnly) writeFileSync(target, next);
  }
}

// Files here with no matching Prisma folder mean a migration was renamed or
// deleted locally. Deleting the generated copy would make Wrangler think the
// migration was never applied, so report instead of silently tidying up.
const expected = new Set(migrations.map((m) => path.basename(m.target)));
const orphans = existsSync(OUT_DIR)
  ? readdirSync(OUT_DIR).filter((f) => f.endsWith(".sql") && !expected.has(f))
  : [];

if (changed.length > 0) {
  console.error("\n✖ These migrations changed after they were synced:\n");
  for (const c of changed) {
    console.error(`   ${c.folder}  (${c.was} → ${c.now})`);
  }
  fail(
    "Wrangler tracks migrations by name, so an edited migration will never be re-applied —\n" +
      "  production would keep the old schema with no warning. Revert the edit and add a new\n" +
      "  migration instead. If this file was genuinely never applied anywhere, delete the copy\n" +
      `  under migrations/ and re-run.`,
  );
}

if (orphans.length > 0) {
  console.error(`\n✖ migrations/ contains files with no matching Prisma migration:\n`);
  for (const o of orphans) console.error(`   ${o}`);
  fail(
    "A migration was renamed or removed locally. If it was already applied to production,\n" +
      "  restoring the original name is the safe fix — Wrangler identifies applied migrations\n" +
      "  by filename.",
  );
}

if (checkOnly) {
  if (created.length > 0 || rewritten.length > 0) {
    console.error(`\n✖ migrations/ is out of date with prisma/migrations/:\n`);
    for (const f of [...created, ...rewritten]) console.error(`   ${f}`);
    fail("Run `npm run cf:migrations:sync` and commit the result.");
  }
  console.log(`✓ migrations/ is in step with prisma/migrations/ (${migrations.length} migrations)`);
  process.exit(0);
}

if (created.length === 0 && rewritten.length === 0) {
  console.log(`✓ Already in sync (${migrations.length} migrations)`);
} else {
  for (const f of created) console.log(`+ ${f}.sql`);
  for (const f of rewritten) console.log(`~ ${f}.sql (header refreshed)`);
  console.log(`\n✓ Synced ${migrations.length} migrations into migrations/`);
  console.log("  Apply them with:  npm run cf:migrate");
}
